/// Rozloží znak na základ a znamienka (NFD) do `ciel`.
fn rozloz(c: u16, ciel: &mut Vec<u16>) {
    match ROZKLAD.chunks_exact(3).find(|t| t[0] == c) {
        Some(t) => {
            rozloz(t[1], ciel);
            ciel.push(t[2]);
        }
        None => ciel.push(c),
    }
}

/// Meno zväzku v tvare HFS+ (UTF-16, rozložené).
pub fn meno_hfs(t: &str) -> Result<Vec<u16>, String> {
    let t = t.trim();
    let t = if t.is_empty() { "Bez názvu" } else { t };
    if t.contains(':') {
        return Err("menovka pre HFS+ nesmie obsahovať dvojbodku".into());
    }
    let mut v = Vec::new();
    for c in t.encode_utf16() {
        rozloz(c, &mut v);
    }
    if v.len() > 255 {
        return Err("menovka je pre HFS+ pridlhá".into());
    }
    Ok(v)
}

/// Čas HFS+ (sekundy od roku 1904).
fn cas_hfs() -> u32 {
    (teraz() + OD_1904) as u32
}

fn be16(b: &mut [u8], o: usize, v: u16) {
    b[o..o + 2].copy_from_slice(&v.to_be_bytes());
}
fn be32(b: &mut [u8], o: usize, v: u32) {
    b[o..o + 4].copy_from_slice(&v.to_be_bytes());
}
fn be64(b: &mut [u8], o: usize, v: u64) {
    b[o..o + 8].copy_from_slice(&v.to_be_bytes());
}

/// Uzol stromu B: popis (14 B), záznamy a na konci posuny záznamov aj voľného miesta.
fn uzol(velkost: u32, druh: i8, vyska: u8, zaznamy: &[Vec<u8>]) -> Vec<u8> {
    let n = velkost as usize;
    let mut u = vec![0u8; n];
    u[8] = druh as u8;
    u[9] = vyska;
    be16(&mut u, 10, zaznamy.len() as u16);
    let mut p = 14;
    for (i, z) in zaznamy.iter().enumerate() {
        be16(&mut u, n - 2 * (i + 1), p as u16);
        u[p..p + z.len()].copy_from_slice(z);
        p += z.len();
    }
    be16(&mut u, n - 2 * (zaznamy.len() + 1), p as u16);
    u
}

/// Vlastnosti stromu B pre hlavičkový uzol.
struct Strom {
    uzol: u32,
    max_kluc: u16,
    uzlov: u32,
    hlbka: u16,
    koren: u32,
    listov: u32,
    pouzitych: u32,
    porovnanie: u8,
    priznaky: u32,
}

/// Hlavičkový uzol (uzol 0): hlavička, 128 B používateľských dát a mapa obsadených uzlov.
fn hlavicka_stromu(s: &Strom) -> Vec<u8> {
    let mut h = vec![0u8; 106];
    be16(&mut h, 0, s.hlbka);
    be32(&mut h, 2, s.koren);
    be32(&mut h, 6, s.listov);
    let list = if s.listov > 0 { s.koren } else { 0 };
    be32(&mut h, 10, list);
    be32(&mut h, 14, list);
    be16(&mut h, 18, s.uzol as u16);
    be16(&mut h, 20, s.max_kluc);
    be32(&mut h, 22, s.uzlov);
    be32(&mut h, 26, s.uzlov - s.pouzitych);
    be32(&mut h, 32, s.uzlov * s.uzol);
    h[37] = s.porovnanie;
    be32(&mut h, 38, s.priznaky);
    let mapa_b = s.uzol as usize - 14 - 106 - 128 - 8;
    let mut mapa = vec![0u8; mapa_b];
    for i in 0..s.pouzitych as usize {
        mapa[i / 8] |= 0x80 >> (i % 8);
    }
    uzol(s.uzol, 1, 0, &[h, vec![0u8; 128], mapa])
}

/// Kľúč katalógu: rodič a meno.
fn kluc(rodic: u32, meno: &[u16]) -> Vec<u8> {
    let mut k = vec![0u8; 8];
    be16(&mut k, 0, (6 + 2 * meno.len()) as u16);
    be32(&mut k, 2, rodic);
    be16(&mut k, 6, meno.len() as u16);
    for c in meno {
        k.extend_from_slice(&c.to_be_bytes());
    }
    k
}

/// Popis vidlice (fork): dĺžka, zhluk, bloky a prvý rozsah.
fn vidlica(b: &mut [u8], o: usize, zaciatok: u32, blokov: u32) {
    be64(b, o, blokov as u64 * BLOK);
    be32(b, o + 8, blokov * BLOK as u32);
    be32(b, o + 12, blokov);
    be32(b, o + 16, zaciatok);
    be32(b, o + 20, blokov);
}

impl Hfs {
    /// Navrhne HFS+ pre oddiel daného počtu sektorov.
    pub fn navrhni(sektory: u64, sektor: u32, nazov: &str) -> Result<Hfs, String> {
        let bajtov = sektory * sektor as u64;
        let blokov = bajtov / BLOK;
        if blokov < 2048 {
            return Err("zväzok je primalý pre HFS+ (aspoň 8 MB)".into());
        }
        if blokov > u32::MAX as u64 {
            return Err("zväzok je priveľký pre HFS+ s blokom 4 KB (nad 16 TB)".into());
        }
        let b = blokov as u32;
        let uzol_katalogu = if bajtov >= 1 << 30 { 8192 } else { 4096 };
        let na_uzol = |u: u32| u / BLOK as u32;
        let zaokruhli = |n: u32, u: u32| n.div_ceil(na_uzol(u)) * na_uzol(u);
        let hfs = Hfs {
            bajtov,
            blokov: b,
            bitmapa: b.div_ceil(BLOK as u32 * 8),
            rozsahy: zaokruhli((b / 128).clamp(128, 1024), UZOL_ROZSAHOV),
            katalog: zaokruhli((b / 128).clamp(128, 4096), uzol_katalogu),
            atributy: zaokruhli((b / 256).clamp(128, 2048), UZOL_ATRIBUTOV),
            uzol_katalogu,
            meno: meno_hfs(nazov)?,
            uuid: jedinecne()[..8].try_into().unwrap_or([1; 8]),
        };
        if hfs.prvy_volny() as u64 + 16 > blokov {
            return Err("zväzok je primalý pre HFS+".into());
        }
        Ok(hfs)
    }

    fn zac_rozsahov(&self) -> u32 {
        1 + self.bitmapa
    }
    fn zac_katalogu(&self) -> u32 {
        self.zac_rozsahov() + self.rozsahy
    }
    fn zac_atributov(&self) -> u32 {
        self.zac_katalogu() + self.katalog
    }
    fn prvy_volny(&self) -> u32 {
        self.zac_atributov() + self.atributy
    }

    /// Bloky na konci, v ktorých leží záložná hlavička (posledných 1024 B oddielu).
    fn koncove(&self) -> std::ops::RangeInclusive<u64> {
        let a = (self.bajtov - 1024) / BLOK;
        let b = ((self.bajtov - 1) / BLOK).min(self.blokov as u64 - 1);
        a..=b
    }

    fn obsadeny(&self, blok: u64) -> bool {
        blok < self.prvy_volny() as u64 || self.koncove().contains(&blok)
    }

    fn volnych(&self) -> u32 {
        let koncove = self.koncove().filter(|&b| b >= self.prvy_volny() as u64).count() as u32;
        self.blokov - self.prvy_volny() - koncove
    }

    /// Hlavička zväzku (512 B), rovnaká na začiatku aj na konci.
    fn hlavicka(&self, cas: u32) -> Vec<u8> {
        let mut h = vec![0u8; 512];
        h[0..2].copy_from_slice(b"H+");
        be16(&mut h, 2, 4);
        be32(&mut h, 4, ATRIBUTY_ZVAZKU);
        h[8..12].copy_from_slice(b"10.0");
        be32(&mut h, 0x10, cas);
        be32(&mut h, 0x14, cas);
        be32(&mut h, 0x1C, cas);
        be32(&mut h, 0x28, BLOK as u32);
        be32(&mut h, 0x2C, self.blokov);
        be32(&mut h, 0x30, self.volnych());
        be32(&mut h, 0x34, self.prvy_volny());
        be32(&mut h, 0x38, 65_536);
        be32(&mut h, 0x3C, 65_536);
        be32(&mut h, 0x40, PRVE_VOLNE_CNID);
        be64(&mut h, 0x48, 1); // kódovanie mien: Mac Roman
        h[0x68..0x70].copy_from_slice(&self.uuid);
        vidlica(&mut h, 0x70, 1, self.bitmapa);
        vidlica(&mut h, 0xC0, self.zac_rozsahov(), self.rozsahy);
        vidlica(&mut h, 0x110, self.zac_katalogu(), self.katalog);
        vidlica(&mut h, 0x160, self.zac_atributov(), self.atributy);
        h
    }

    /// Katalóg: hlavičkový uzol a list s koreňovým priečinkom (meno zväzku) a jeho vláknom.
    fn katalog(&self, cas: u32) -> (Vec<u8>, Vec<u8>) {
        let u = self.uzol_katalogu;
        let uzlov = self.katalog * BLOK as u32 / u;
        let hlavicka = hlavicka_stromu(&Strom {
            uzol: u,
            max_kluc: 516,
            uzlov,
            hlbka: 1,
            koren: 1,
            listov: 2,
            pouzitych: 2,
            porovnanie: 0xCF,
            priznaky: 6,
        });
        let mut priecinok = kluc(1, &self.meno);
        let mut z = vec![0u8; 88];
        be16(&mut z, 0, 1); // záznam priečinka
        be32(&mut z, 8, 2); // číslo koreňového priečinka
        be32(&mut z, 12, cas);
        be32(&mut z, 16, cas);
        priecinok.extend_from_slice(&z);
        let mut vlakno = kluc(2, &[]);
        let mut z = vec![0u8; 8];
        be16(&mut z, 0, 3); // vlákno priečinka
        be32(&mut z, 4, 1);
        z.extend_from_slice(&(self.meno.len() as u16).to_be_bytes());
        for c in &self.meno {
            z.extend_from_slice(&c.to_be_bytes());
        }
        vlakno.extend_from_slice(&z);
        (hlavicka, uzol(u, -1, 1, &[priecinok, vlakno]))
    }

    fn prazdny_strom(uzol: u32, blokov: u32, max_kluc: u16, priznaky: u32) -> Vec<u8> {
        hlavicka_stromu(&Strom {
            uzol,
            max_kluc,
            uzlov: blokov * BLOK as u32 / uzol,
            hlbka: 0,
            koren: 0,
            listov: 0,
            pouzitych: 1,
            porovnanie: 0,
            priznaky,
        })
    }

    /// Bajty bitmapy pridelenia od bajtu `od` (bit 7 prvého bajtu = blok 0).
    fn bitmapa_kus(&self, od: u64, n: usize) -> Vec<u8> {
        let mut v = vec![0u8; n];
        let prvy = self.prvy_volny() as u64;
        for (i, b) in v.iter_mut().enumerate() {
            let blok0 = (od + i as u64) * 8;
            if blok0 >= self.blokov as u64 {
                break;
            }
            if blok0 + 8 <= prvy {
                *b = 0xFF;
                continue;
            }
            for j in 0..8 {
                let blok = blok0 + j;
                if blok < self.blokov as u64 && self.obsadeny(blok) {
                    *b |= 0x80 >> j;
                }
            }
        }
        v
    }

    /// Zapíše prázdny zväzok od bajtu `posun`.
    pub fn naformatuj(
        &self,
        c: &mut dyn Ciel,
        posun: u64,
        priebeh: &mut dyn FnMut(u64, u64),
        zrus: &AtomicBool,
    ) -> io::Result<()> {
        let cas = cas_hfs();
        let hlavicka = self.hlavicka(cas);
        let at = |b: u32| posun + b as u64 * BLOK;
        let celkom = self.prvy_volny() as u64 * BLOK + BLOK;
        let mut hotovo = 0u64;
        // blok 0: zavádzacie bloky (nuly) a hlavička na 1024
        let mut b0 = vec![0u8; BLOK as usize];
        b0[1024..1536].copy_from_slice(&hlavicka);
        c.zapis(posun, &b0)?;
        // bitmapa po kusoch
        let bitmapa_b = self.bitmapa as u64 * BLOK;
        let mut p = 0u64;
        while p < bitmapa_b {
            if zrus.load(Ordering::Relaxed) {
                return Err(io::Error::other("zrušené"));
            }
            let n = (bitmapa_b - p).min(1 << 20) as usize;
            ciel::zapis_vsetko(c, at(1) + p, &self.bitmapa_kus(p, n))?;
            p += n as u64;
            priebeh(BLOK + p, celkom);
        }
        hotovo += BLOK + bitmapa_b;
        // stromy: hlavičkový uzol (pri katalógu aj list), zvyšok nuly
        let (kat_hlavicka, kat_list) = self.katalog(cas);
        let mut kat = kat_hlavicka;
        kat.extend_from_slice(&kat_list);
        let stromy = [
            (self.zac_rozsahov(), self.rozsahy, Hfs::prazdny_strom(UZOL_ROZSAHOV, self.rozsahy, 10, 2)),
            (self.zac_katalogu(), self.katalog, kat),
            (self.zac_atributov(), self.atributy, Hfs::prazdny_strom(UZOL_ATRIBUTOV, self.atributy, 266, 6)),
        ];
        for (zac, blokov, zaciatok) in stromy {
            ciel::zapis_vsetko(c, at(zac), &zaciatok)?;
            let zvysok = blokov as u64 * BLOK - zaciatok.len() as u64;
            let h0 = hotovo + zaciatok.len() as u64;
            ciel::vynuluj(
                c,
                at(zac) + zaciatok.len() as u64,
                zvysok,
                &mut |h, _| priebeh(h0 + h, celkom),
                zrus,
            )?;
            hotovo += blokov as u64 * BLOK;
        }
        // záložná hlavička: 1024 B pred koncom oddielu (posledných 4 KB sa prepíše)
        let mut koniec = vec![0u8; BLOK as usize];
        koniec[3072..3584].copy_from_slice(&hlavicka);
        c.zapis(posun + self.bajtov - BLOK, &koniec)?;
        priebeh(celkom, celkom);
        Ok(())
    }
}

impl crate::subory::Zvazok for Hfs {
    fn klaster_b(&self) -> u64 {
        BLOK
    }
    fn naplnene(
        &self,
        c: &mut dyn Ciel,
        posun: u64,
        strom: &crate::subory::Strom,
        _citaj: &mut crate::subory::Citaj,
        priebeh: &mut dyn FnMut(u64, u64),
        zrus: &AtomicBool,
    ) -> io::Result<Vec<crate::subory::Zapisany>> {
        if !strom.subory().is_empty() || strom.uzly.len() > 1 {
            return Err(io::Error::other("zápis súborov na HFS+ zatiaľ nie je – len formátovanie"));
        }
        self.naformatuj(c, posun, priebeh, zrus)?;
        Ok(Vec::new())
    }
    fn over(&self, zaciatok: &[u8]) -> bool {
        zaciatok.len() >= 1536 && &zaciatok[1024..1026] == b"H+" && zaciatok[1027] == 4
    }
    fn zmesti_sa(&self, strom: &crate::subory::Strom) -> bool {
        strom.uzly.len() <= 1
    }
}

#[cfg(test)]
mod skusky {
    use super::*;
    use crate::ciel::Pamat;

    #[test]
    fn rozklad_mien() {
        assert_eq!(meno_hfs("Škola").unwrap(), [0x53, 0x30C, 0x6B, 0x6F, 0x6C, 0x61]);
        assert_eq!(meno_hfs("Ấ").unwrap(), [0x41, 0x302, 0x301], "dva kroky rozkladu");
        assert_eq!(meno_hfs("").unwrap().len(), 10, "Bez názvu: á = a + ´");
        assert!(meno_hfs("a:b").is_err());
        assert!(ROZKLAD.chunks_exact(3).is_sorted_by_key(|t| t[0]), "tabuľka je zoradená");
    }

    #[test]
    fn rozvrh_a_podpis() {
        let mut p = Pamat::nova(64 << 20, 512);
        let h = Hfs::navrhni((64 << 20) / 512, 512, "Skúška").unwrap();
        assert_eq!(h.blokov, 16_384);
        assert_eq!(h.bitmapa, 1);
        h.naformatuj(&mut p, 0, &mut |_, _| {}, &AtomicBool::new(false)).unwrap();
        let mut z = vec![0u8; 4096];
        p.citaj(0, &mut z).unwrap();
        assert!(crate::subory::Zvazok::over(&h, &z));
        let mut k = vec![0u8; 4096];
        p.citaj((64 << 20) - 4096, &mut k).unwrap();
        assert_eq!(&k[3072..3584], &z[1024..1536], "záložná hlavička");
        // bitmapa: obsadené bloky od 0 po prvý voľný a posledný blok
        let mut b = vec![0u8; 4096];
        p.citaj(4096, &mut b).unwrap();
        let prvy = h.prvy_volny() as usize;
        assert_eq!(b[0], 0xFF);
        assert_eq!(b[prvy / 8] & (0x80 >> (prvy % 8)), 0, "prvý voľný blok");
        assert_eq!(b[2047], 0x01, "posledný blok so zálohou");
        let volne = u32::from_be_bytes(z[1024 + 0x30..1024 + 0x34].try_into().unwrap());
        let obsadene: u32 = b[..2048].iter().map(|x| x.count_ones()).sum();
        assert_eq!(volne + obsadene, h.blokov);
    }
}
